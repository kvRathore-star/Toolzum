/** Generates public/_redirects (301s for renamed tools) below a GENERATED marker; preserves hand-written rules above it (npm run gen:redirects). */
const fs = require('fs');
const path = require('path');

const PUBLIC_DIR = path.join(__dirname, '../public');
const REDIRECTS_PATH = path.join(PUBLIC_DIR, '_redirects');
const GENERATED_MARKER = '# ==== GENERATED BY scripts/generate-redirects.js — DO NOT EDIT BELOW ====';

function parseToolRedirects() {
  const file = path.join(__dirname, '../src/registry/tools-constants.ts');
  const content = fs.readFileSync(file, 'utf-8');

  const block = content.match(/export const TOOL_REDIRECTS[\s\S]*?=\s*\{([\s\S]*?)\n\};/);
  if (!block) throw new Error('Could not find TOOL_REDIRECTS block in tools-constants.ts');

  const entries = [];
  const entryRegex = /^\s*"([a-z0-9-]+)":\s*\{([^}]*)\},?\s*$/gm;
  let m;
  while ((m = entryRegex.exec(block[1])) !== null) {
    const [, key, body] = m;
    const category = body.match(/category:\s*"([^"]+)"/);
    const slug = body.match(/slug:\s*"([^"]+)"/);
    const query = body.match(/query:\s*"([^"]+)"/);
    const sourceCategoryMatch = body.match(/sourceCategory:\s*("(?:[^"]+)"|\[[^\]]*\])/);

    let sourceCategory;
    if (sourceCategoryMatch) {
      const raw = sourceCategoryMatch[1];
      if (raw.startsWith('[')) {
        sourceCategory = (raw.match(/"[^"]+"/g) || []).map(s => s.slice(1, -1));
      } else {
        sourceCategory = [raw.slice(1, -1)];
      }
    }

    entries.push({
      slug: key,
      category: category ? category[1] : null,
      targetSlug: slug ? slug[1] : null,
      sourceCategory,
      query: query ? query[1] : null,
    });
  }

  return entries;
}

function slugifyCategory(cat) {
  if (!cat) return null;
  if (cat === "Growth & Marketing") return "growth-metrics";
  return cat.toLowerCase().replace(/\s+/g, '-');
}

function deriveRules(entries) {
  const rules = new Map();

  for (const entry of entries) {
    const catSlug = slugifyCategory(entry.category);
    if (!catSlug || !entry.targetSlug) continue;
    // Optional ?query= preserved through the redirect (e.g. ?from=avi so the
    // merged tool page can preselect the visitor's original intent).
    const suffix = entry.query ? `?${entry.query}` : "";

    // Same-category slug rename: /cat/old-slug → /cat/new-slug/
    if (entry.slug !== entry.targetSlug) {
      rules.set(`/${catSlug}/${entry.slug}`, `/${catSlug}/${entry.targetSlug}/${suffix}`);
    }

    // Cross-category migration: /old-cat/slug → /new-cat/slug/
    for (const src of entry.sourceCategory || []) {
      const srcSlug = slugifyCategory(src);
      if (srcSlug) {
        rules.set(`/${srcSlug}/${entry.slug}`, `/${catSlug}/${entry.targetSlug}/${suffix}`);
      }
    }
  }

  return rules;
}

const DYNAMIC_RULE_PATTERN = /\*|:[\w-]/;

function isDynamicRule(line) {
  return DYNAMIC_RULE_PATTERN.test(line.trim());
}

function parseStaticRules(content) {
  const staticLines = [];
  const staticSources = new Set();
  const dynamicRules = [];
  let inGeneratedSection = false;
  for (const line of content.split('\n')) {
    if (line.trim().startsWith(GENERATED_MARKER)) {
      inGeneratedSection = true;
      continue;
    }
    if (line.trim() && !line.trim().startsWith('#')) {
      const parts = line.trim().split(/\s+/);
      if (parts.length >= 3) {
        if (isDynamicRule(line)) {
          dynamicRules.push(line.trim());
          if (!inGeneratedSection) continue; // drop from static block; re-appended at end
        }
        if (!inGeneratedSection) staticSources.add(parts[0].replace(/\/$/, ''));
      }
    }
    if (!inGeneratedSection) staticLines.push(line);
  }
  return { staticLines, staticSources, dynamicRules };
}

function generateRedirects() {
  console.log('Generating _redirects from TOOL_REDIRECTS...');

  const entries = parseToolRedirects();
  const derived = deriveRules(entries);
  console.log(`Derived ${derived.size} redirect rules from ${entries.length} TOOL_REDIRECTS entries`);

  const existing = fs.existsSync(REDIRECTS_PATH) ? fs.readFileSync(REDIRECTS_PATH, 'utf-8') : '';
  const { staticLines, staticSources, dynamicRules } = parseStaticRules(existing);

  // Keep the static section verbatim (including trailing blank line before marker, if any).
  // Dynamic rules (splats/placeholders) are removed from it and re-appended at the very end:
  // Cloudflare's _redirects parser treats everything after the first dynamic rule as dynamic
  // and silently drops the tail once 100 dynamic rules are exceeded. Static-first ordering
  // keeps all static rules on the 2,000-static budget.
  const staticBlock = staticLines.join('\n').replace(/\s+$/, '') + '\n';

  const generatedRules = [];
  for (const [src, dest] of [...derived.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    if (staticSources.has(src)) continue; // hand-authored rule already covers this source
    generatedRules.push(`${src}/   ${dest}   301`);
    generatedRules.push(`${src}    ${dest}   301`);
  }

  const dynamicBlock = dynamicRules.length
    ? `# ==== DYNAMIC RULES (keep last — everything after the first splat/placeholder counts as dynamic) ====\n${dynamicRules.join('\n')}\n`
    : '';

  const output = (generatedRules.length || dynamicRules.length)
    ? `${staticBlock}\n${GENERATED_MARKER}\n# Auto-generated from TOOL_REDIRECTS. Run: npm run gen:redirects\n${generatedRules.join('\n')}\n${dynamicBlock}`
    : staticBlock;

  if (!fs.existsSync(PUBLIC_DIR)) {
    fs.mkdirSync(PUBLIC_DIR, { recursive: true });
  }

  fs.writeFileSync(REDIRECTS_PATH, output, 'utf-8');
  console.log(`_redirects updated: ${generatedRules.length} generated lines (${generatedRules.length / 2} rules), static section preserved`);
}

generateRedirects();
